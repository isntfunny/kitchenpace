#!/usr/bin/env node
// Generates the bundled ingredient icons (KUC-125) from the IconOven Iconify set
// (MIT, https://iconoven.com): only the icons listed in
// scripts/ingredient-icons/manifest.json end up in the repo, so the client never
// bundles or fetches the whole set.
//
//   node scripts/generate-ingredient-icons.mjs [path/to/iconoven/icons.json]
//
// Without a path it reads node_modules/@iconify-json/iconoven/icons.json.
// Writes:
//   shared/ingredient-icons/names.generated.ts   names by group (worker + client)
//   src/lib/icons/iconoven-food.ts               SVG bodies by name (client only)

import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = resolve(
    process.argv[2] ?? join(root, 'node_modules/@iconify-json/iconoven/icons.json'),
);
if (!existsSync(sourcePath)) {
    console.error(`Iconify set not found: ${sourcePath}`);
    process.exit(1);
}

const manifest = JSON.parse(
    readFileSync(join(root, 'scripts/ingredient-icons/manifest.json'), 'utf8'),
);
const set = JSON.parse(readFileSync(sourcePath, 'utf8'));
if (set.prefix !== 'iconoven') {
    console.error(`Expected the iconoven set, got "${set.prefix}"`);
    process.exit(1);
}

const groups = ['food', 'extraFood', 'household'];
const all = groups.flatMap((group) => manifest[group]);
const duplicates = all.filter((name, index) => all.indexOf(name) !== index);
if (duplicates.length > 0) throw new Error(`Duplicate icons in the manifest: ${duplicates}`);
const notInSet = [...all, ...manifest.notForEnrichment].filter((name) => !set.icons[name]);
if (notInSet.length > 0) throw new Error(`Not in the IconOven set: ${notInSet}`);
const notAllowed = manifest.notForEnrichment.filter((name) => !all.includes(name));
if (notAllowed.length > 0) throw new Error(`notForEnrichment is not in a group: ${notAllowed}`);

const list = (names) => `[\n${names.map((name) => `    '${name}',`).join('\n')}\n]`;
const header = `// Generated by scripts/generate-ingredient-icons.mjs from the IconOven set
// (MIT, https://iconoven.com). Do not edit; change scripts/ingredient-icons/manifest.json.\n`;

const names = `${header}
/** IconOven food category (iconoven.com) */
export const FOOD_ICON_NAMES = ${list(manifest.food)} as const;

/** Further food icons from outside that category */
export const EXTRA_FOOD_ICON_NAMES = ${list(manifest.extraFood)} as const;

/** Household and cleaning items (free-text shopping list entries) */
export const HOUSEHOLD_ICON_NAMES = ${list(manifest.household)} as const;

/** Allowed but not offered to the enrichment model: utensils, marks, the neutral icon */
export const NOT_FOR_ENRICHMENT_ICON_NAMES: readonly string[] = ${list(manifest.notForEnrichment)};
`;

const bodies = `${header}
/** SVG bodies (24x24, stroke="currentColor") of the allowed icons */
export const ICONOVEN_BODIES = {
${all.map((name) => `    '${name}': ${JSON.stringify(set.icons[name].body)},`).join('\n')}
} as const;

export const ICONOVEN_VIEWBOX = ${set.width ?? 24};
`;

const targets = [
    ['shared/ingredient-icons/names.generated.ts', names],
    ['src/lib/icons/iconoven-food.ts', bodies],
];
for (const [file, content] of targets) writeFileSync(join(root, file), content);
execFileSync('npx', ['prettier', '--write', ...targets.map(([file]) => join(root, file))], {
    cwd: root,
    stdio: 'inherit',
});
console.log(`Wrote ${all.length} icons`);
